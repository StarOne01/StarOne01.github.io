#!/usr/bin/env node
/**
 * Regenerates src/data/contribs.ts from GitHub.
 *
 *   node scripts/sync-contribs.mjs            # unauthenticated (60 req/hr)
 *   GITHUB_TOKEN=... node scripts/sync-contribs.mjs
 *
 * Uses the search API, so one request covers every PR.
 */

import fs from "node:fs";
import path from "node:path";

const AUTHOR = "StarOne01";
const REPO = "llvm/llvm-project";
const SOURCE = `https://github.com/${REPO}/pulls?q=is%3Apr+author%3A${AUTHOR}`;
const OUT = path.join(process.cwd(), "src/data/contribs.ts");

const groups = [
  {
    id: "scf",
    label: "MLIR · SCF",
    blurb:
      "Loop peeling, canonicalization, and specialization in the structured control flow dialect.",
  },
  {
    id: "vector",
    label: "MLIR · Vector",
    blurb:
      "Contraction, transpose, and VectorToSCF lowering fixes.",
  },
  {
    id: "nvptx",
    label: "LLVM · NVPTX",
    blurb: "v2i32 bswap and truncating stores for the PTX backend.",
  },
  {
    id: "x86",
    label: "LLVM · X86",
    blurb: "_Float16 lowering for FABS, FNEG, and FCOPYSIGN.",
  },
  {
    id: "clang",
    label: "Clang · Sema",
    blurb: "Diagnostics for function-like macro references without parentheses.",
  },
  {
    id: "libc",
    label: "libc · Docs",
    blurb: "POSIX header coverage for the libc implementation status docs.",
  },
];

function groupFor(title) {
  const t = title.toLowerCase();
  if (t.includes("[mlir][scf]")) return "scf";
  if (t.includes("[mlir][vector]")) return "vector";
  if (t.includes("[nvptx]")) return "nvptx";
  if (t.includes("[x86]")) return "x86";
  if (t.includes("[clang]")) return "clang";
  if (t.includes("[libc]")) return "libc";
  throw new Error(`No group for title: ${title}`);
}

function cleanTitle(title) {
  return title
    .replace(/^(\s*\[[^\]]+\])+\s*/, "")
    .replace(/\s+/g, " ")
    .trim();
}

async function fetchPage(page) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "starone01-portfolio-sync",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  const url = new URL("https://api.github.com/search/issues");
  url.searchParams.set("q", `repo:${REPO} is:pr author:${AUTHOR}`);
  url.searchParams.set("per_page", "100");
  url.searchParams.set("page", String(page));

  const res = await fetch(url, { headers });
  if (!res.ok) {
    throw new Error(`GitHub API ${res.status}: ${await res.text()}`);
  }
  return res.json();
}

function statusFor(item) {
  if (item.pull_request?.merged_at) return "merged";
  return item.state === "open" ? "open" : "closed";
}

const first = await fetchPage(1);
const items = [...first.items];
for (let page = 2; page <= Math.ceil(first.total_count / 100); page += 1) {
  const next = await fetchPage(page);
  items.push(...next.items);
}

const seen = new Set();
const contributions = items
  .filter((item) => {
    if (seen.has(item.number)) return false;
    seen.add(item.number);
    return true;
  })
  .map((item) => ({
    number: item.number,
    title: cleanTitle(item.title),
    date: item.created_at.slice(0, 10),
    status: statusFor(item),
    group: groupFor(item.title),
    url: item.html_url,
  }))
  .sort((a, b) => b.date.localeCompare(a.date) || b.number - a.number);

const lines = contributions.map(
  (c) =>
    `  { number: ${c.number}, title: ${JSON.stringify(c.title)}, date: ${JSON.stringify(
      c.date
    )}, status: ${JSON.stringify(c.status)}, group: ${JSON.stringify(c.group)}, url: ${JSON.stringify(
      c.url
    )} },`
);

const file = `// Generated by scripts/sync-contribs.mjs — do not edit by hand.
// Source: ${SOURCE}
// Synced: ${new Date().toISOString().slice(0, 10)}

export const contributionsSource = ${JSON.stringify(SOURCE)};

export type ContributionStatus = "merged" | "open" | "closed";
export type ContributionGroupId = ${groups.map((g) => JSON.stringify(g.id)).join(" | ")};

export type Contribution = {
  number: number;
  title: string;
  date: string;
  status: ContributionStatus;
  group: ContributionGroupId;
  url: string;
};

export const contributionGroups = [
${groups
  .map(
    (g) =>
      `  { id: ${JSON.stringify(g.id)}, label: ${JSON.stringify(
        g.label
      )}, blurb: ${JSON.stringify(g.blurb)} },`
  )
  .join("\n")}
] as const;

export const contributions: readonly Contribution[] = [
${lines.join("\n")}
];
`;

fs.writeFileSync(OUT, file);
console.log(`Wrote ${contributions.length} contributions to ${path.relative(process.cwd(), OUT)}`);
