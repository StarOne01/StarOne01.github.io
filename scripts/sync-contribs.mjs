#!/usr/bin/env node
/**
 * Regenerates src/data/contribs.ts from the GitHub REST API.
 *
 *   node scripts/sync-contribs.mjs            # unauthenticated (rate-limited)
 *   GITHUB_TOKEN=... node scripts/sync-contribs.mjs
 *
 * CI runs this before the build. The search endpoint returns every authored
 * PR in one paginated query, and the public membership endpoint verifies the
 * llvm organization badge.
 */

import fs from "node:fs";
import path from "node:path";

const AUTHOR = "StarOne01";
const ORG = "llvm";
const REPO = "llvm/llvm-project";
const SOURCE = `https://github.com/${REPO}/pulls?q=is%3Apr+author%3A${AUTHOR}`;
const OUT = path.join(process.cwd(), "src/data/contribs.ts");

const groups = [
  {
    id: "scf",
    label: "MLIR · SCF",
    blurb:
      "Loop peeling, canonicalization, and specialization in the structured control flow dialect.",
  },
  {
    id: "vector",
    label: "MLIR · Vector",
    blurb: "Contraction, transpose, and VectorToSCF lowering fixes.",
  },
  {
    id: "mlir",
    label: "MLIR · Core",
    blurb: "Cross-cutting MLIR changes and lowering fixes.",
  },
  {
    id: "nvptx",
    label: "LLVM · NVPTX",
    blurb: "v2i32 bswap and truncating stores for the PTX backend.",
  },
  {
    id: "x86",
    label: "LLVM · X86",
    blurb: "_Float16 lowering for FABS, FNEG, and FCOPYSIGN.",
  },
  {
    id: "clang",
    label: "Clang · Sema",
    blurb: "Diagnostics for function-like macro references without parentheses.",
  },
  {
    id: "libc",
    label: "libc · Docs",
    blurb: "POSIX header coverage for the libc implementation status docs.",
  },
  {
    id: "other",
    label: "llvm-project · Other",
    blurb: "Other fixes and reviews across the monorepo.",
  },
];

function groupFor(title, labels = []) {
  const t = title.toLowerCase();
  const tags = new Set(labels.map((label) => label.name.toLowerCase()));

  if (tags.has("mlir:scf") || t.includes("[mlir][scf]")) return "scf";
  if (
    tags.has("mlir:vector") ||
    tags.has("mlir:vectorops") ||
    t.includes("[mlir][vector]")
  ) {
    return "vector";
  }
  if (tags.has("backend:nvptx") || t.includes("[nvptx]")) return "nvptx";
  if (tags.has("backend:x86") || t.includes("[x86]")) return "x86";
  if (tags.has("clang") || t.includes("[clang]")) return "clang";
  if (tags.has("libc") || t.includes("[libc]")) return "libc";
  if (tags.has("mlir") || t.includes("[mlir]")) return "mlir";
  return "other";
}

function cleanTitle(title) {
  return title
    .replace(/^(\s*\[[^\]]+\])+\s*/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function apiHeaders() {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "starone01-portfolio-sync",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }
  return headers;
}

async function fetchPage(page) {
  const url = new URL("https://api.github.com/search/issues");
  url.searchParams.set("q", `repo:${REPO} is:pr author:${AUTHOR}`);
  url.searchParams.set("per_page", "100");
  url.searchParams.set("page", String(page));

  const res = await fetch(url, { headers: apiHeaders() });
  if (!res.ok) {
    throw new Error(`GitHub API ${res.status}: ${await res.text()}`);
  }
  return res.json();
}

async function isOrgMember() {
  const res = await fetch(
    `https://api.github.com/orgs/${ORG}/public_members/${AUTHOR}`,
    { headers: apiHeaders() }
  );
  if (res.status === 204) return true;
  if (res.status === 404) return false;
  throw new Error(`GitHub API ${res.status}: ${await res.text()}`);
}

function statusFor(item) {
  if (item.pull_request?.merged_at) return "merged";
  return item.state === "open" ? "open" : "closed";
}

function dateFor(item) {
  const date =
    item.pull_request?.merged_at ?? item.closed_at ?? item.created_at;
  return date.slice(0, 10);
}

const [first, member] = await Promise.all([fetchPage(1), isOrgMember()]);
const items = [...first.items];
for (let page = 2; page <= Math.ceil(first.total_count / 100); page += 1) {
  const next = await fetchPage(page);
  items.push(...next.items);
}

const seen = new Set();
const contributions = items
  .filter((item) => {
    if (seen.has(item.number)) return false;
    seen.add(item.number);
    return true;
  })
  .map((item) => ({
    number: item.number,
    title: cleanTitle(item.title),
    date: dateFor(item),
    status: statusFor(item),
    group: groupFor(item.title, item.labels),
    url: item.html_url,
  }))
  .sort((a, b) => b.date.localeCompare(a.date) || b.number - a.number);

const lines = contributions.map(
  (c) =>
    `  { number: ${c.number}, title: ${JSON.stringify(c.title)}, date: ${JSON.stringify(
      c.date
    )}, status: ${JSON.stringify(c.status)}, group: ${JSON.stringify(c.group)}, url: ${JSON.stringify(
      c.url
    )} },`
);

const file = `// Generated by scripts/sync-contribs.mjs — do not edit by hand.
// Source: ${SOURCE}
// Membership: https://api.github.com/orgs/${ORG}/public_members/${AUTHOR}
// Synced: ${new Date().toISOString().slice(0, 10)}

export const contributionsSource = ${JSON.stringify(SOURCE)};

export const llvmOrg = {
  name: ${JSON.stringify(ORG)},
  url: ${JSON.stringify(`https://github.com/${ORG}`)},
  member: ${member},
} as const;

export type ContributionStatus = "merged" | "open" | "closed";
export type ContributionGroupId = ${groups.map((g) => JSON.stringify(g.id)).join(" | ")};

export type Contribution = {
  number: number;
  title: string;
  date: string;
  status: ContributionStatus;
  group: ContributionGroupId;
  url: string;
};

export const contributionGroups = [
${groups
  .map(
    (g) =>
      `  { id: ${JSON.stringify(g.id)}, label: ${JSON.stringify(
        g.label
      )}, blurb: ${JSON.stringify(g.blurb)} },`
  )
  .join("\n")}
] as const;

export const contributions: readonly Contribution[] = [
${lines.join("\n")}
];
`;

fs.writeFileSync(OUT, file);
console.log(
  `Wrote ${contributions.length} contributions to ${path.relative(
    process.cwd(),
    OUT
  )} (${ORG} member: ${member})`
);
